#!/usr/bin/env bash
# Builds the synthetic fixture workspace (git repos, branches and worktrees) from
# fixtures/templates. Idempotent and deterministic: fixed author, commit dates and mtimes.
#
# Usage: scripts/make-fixtures.sh [out-dir]     (default: fixtures/workspace)
# The output directory is deleted and rebuilt only if it is empty or has the
# .quire-fixtures marker written by this script. See fixtures/README.md.
set -euo pipefail

repo_root=$(cd "$(dirname "$0")/.." && pwd)
tpl="$repo_root/fixtures/templates"
out=${1:-"$repo_root/fixtures/workspace"}
marker=.quire-fixtures

if [ -e "$out" ]; then
  if [ -f "$out/$marker" ] || [ -z "$(ls -A "$out")" ]; then
    rm -rf "$out"
  else
    echo "refusing to delete $out: not empty and no $marker marker" >&2
    exit 1
  fi
fi
mkdir -p "$out/projects" "$out/external"
out=$(cd "$out" && pwd)
echo "generated by scripts/make-fixtures.sh; safe to delete" > "$out/$marker"

# Isolate git from the user's config (signing, hooks, templates) and pin identity and time.
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 TZ=UTC
export GIT_AUTHOR_NAME="Fixture Bot" GIT_AUTHOR_EMAIL="fixtures@example.com"
export GIT_COMMITTER_NAME="Fixture Bot" GIT_COMMITTER_EMAIL="fixtures@example.com"
g() {
  git -c init.defaultBranch=main -c commit.gpgsign=false -c core.hooksPath=/dev/null \
    -c core.autocrlf=false -c init.templateDir= "$@"
}
commit() { # <date> <repo> <message>
  GIT_AUTHOR_DATE="$1" GIT_COMMITTER_DATE="$1" g -C "$2" commit -q -m "$3"
}
decoy() { # <dir>: a .specs folder that the scanner must ignore
  mkdir -p "$1"
  printf '# decoy\n\nThis spec lives inside an ignored folder and must never be listed.\n' > "$1/spec.md"
}

# --- acme_gateway: has origin, two worktrees -------------------------------------------
gw="$out/projects/acme_gateway"
cp -R "$tpl/acme_gateway" "$gw"
g init -q "$gw"
g -C "$gw" remote add origin git@git.example.com:acme/acme_gateway.git
g -C "$gw" add -A
commit "2026-01-05T09:00:00Z" "$gw" "chore: initial synthetic content"
decoy "$gw/node_modules/left-pad/.specs/features/decoy-1-node-modules"
decoy "$gw/target/debug/.specs/features/decoy-2-target"

# Identical copy, inside the scan path (outside the repo folder).
g -C "$gw" worktree add -q -b feat/acme-142-service-tokens "$out/projects/.worktrees/acme-142/acme_gateway"

# Divergent copy, outside the scan path: only `git worktree list` finds it (DSC-03).
wt="$out/external/acme-170/acme_gateway"
g -C "$gw" worktree add -q -b feat/acme-170-rate-limit "$wt"
tasks="$wt/.specs/features/acme-170-rate-limit/tasks.md"
sed 's/^- \[ \] T2: Resposta 429 com Retry-After$/- [x] T2: Resposta 429 com Retry-After (2b3c4d5)/' "$tasks" > "$tasks.tmp"
mv "$tasks.tmp" "$tasks"
g -C "$wt" add -A
commit "2026-01-12T15:00:00Z" "$wt" "feat: answer 429 with Retry-After"

# --- acme_billing: no origin -------------------------------------------------------------
bl="$out/projects/acme_billing"
cp -R "$tpl/acme_billing" "$bl"
# Text formats for the v0.2 write tests and E2E (T26). Made byte by byte here, because
# .gitattributes forces LF on every file of this repository.
fmt="$bl/.specs/features/bill-40-refunds"
printf '\357\273\277# Formato: BOM e CRLF\r\n\r\nLinha com acentuação.\r\n\r\n- [ ] T1: conferir o diff\r\n' > "$fmt/formato-crlf-bom.md"
printf '# Formato: sem newline final\n\nA última linha não termina com quebra.' > "$fmt/formato-sem-newline.md"
printf '# Formato: fins de linha mistos\r\n\r\nEsta linha usa CRLF.\r\nEsta usa LF.\nE esta CRLF de novo.\r\n' > "$fmt/formato-misto.md"
unix_only=1
case "$(uname -s)" in MINGW* | MSYS* | CYGWIN*) unix_only=0 ;; esac
if [ "$unix_only" = 1 ]; then
  # A link to a file outside the spec folder: a save must write the target and keep the link.
  mkdir -p "$bl/docs"
  printf '# Alvo do link\n\nEste arquivo é editado pelo link formato-link.md.\n' > "$bl/docs/link-alvo.md"
  ln -s ../../../docs/link-alvo.md "$fmt/formato-link.md"
  printf '# Formato: somente leitura\n\nSalvar tem de oferecer uma cópia.\n' > "$fmt/formato-somente-leitura.md"
fi
g init -q "$bl"
g -C "$bl" add -A
commit "2026-01-03T09:00:00Z" "$bl" "chore: initial synthetic content"
decoy "$bl/dist/.specs/features/decoy-3-dist"

# Read-only after the commit (git keeps only the executable bit); Unix only, so tests that
# delete fixture folders keep working on Windows.
if [ "$unix_only" = 1 ]; then chmod 444 "$fmt/formato-somente-leitura.md"; fi

# --- deterministic mtimes ----------------------------------------------------------------
find "$out" -name .git -prune -o -exec touch -t 202601101000 {} +
find "$wt/.specs/features/acme-170-rate-limit" -type f -exec touch -t 202601121500 {} +

echo "fixtures ready in $out"
